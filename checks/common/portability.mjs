const isRecord = value => value !== null && typeof value === 'object' && !Array.isArray(value);
const nodeTypes = new Set(['text','file','link','group']);
const canInspectNode = node => isRecord(node) && typeof node.id === 'string' && !!node.id.trim() && nodeTypes.has(node.type) &&
	['x','y','width','height'].every(key => Number.isSafeInteger(node[key])) &&
	(node.color === undefined || typeof node.color === 'string' && /^(?:#[0-9a-f]{6}|[1-6])$/iu.test(node.color));

function noteCoverage(check, note, {tr, addReason}) {
	const {dynamic, problem, cacheUnavailable, file} = note;
	if (dynamic.length) {
		check.coverage.skipped += dynamic.length;
		const message = tr('查询、公式与自动化代码块的生成内容不参与链接检查。','The link check skips content generated by queries, formulas, and automation blocks.');
		addReason(check, message);
		for (const {language,line} of dynamic) check.diagnostics.push({severity:'info',code:'dynamic-block-skipped',file,line,evidence:language,message});
	}
	if (cacheUnavailable) check.coverage.unknown++;
	if (problem) {
		check.coverage.unknown++;
		const message = problem.code === 'unclosed-frontmatter'
			? tr('未找到 YAML 属性的结束标记，无法完整检查属性和正文中的链接。','Could not verify all links in the frontmatter and body because the frontmatter has no closing delimiter.')
			: tr('YAML 属性无效，无法完整检查属性中的链接。','Could not verify all links in the frontmatter because it contains invalid YAML.');
		check.diagnostics.push({severity:'info',code:'unverified-property-links',file,line:problem.line,message});
		addReason(check, tr('部分 Markdown 属性中的链接未能验证。','Some links in Markdown frontmatter could not be verified.'));
	}
}

function noteLinkCoverage(check, {tr, addReason}) {
	if (check.coverage.unknown)
		addReason(check, tr('部分结果需要 Obsidian 索引、受支持的链接语法或可读文件才能确认。','Some results need the Obsidian index, supported link syntax, or readable files to be verified.'));
}

export default function checkPortability({result: check, notes, canvases, candidateMatches, canvasMatches, canvasIncluded}, tools) {
	const {tr, addReason, validText, recordChecked, recordLinkPlaceholder} = tools;
	function inspect({link, found, cross}, matches, position, details) {
		const matching = matches.length > 1 && tr('同名候选','Same-name candidates') + ' ' + matches.join(tr('、',', '));
		if (found.status === 'unknown') check.coverage.unknown++;
		else {
			const label = matches.length ? tr('引用目标归属与同名候选','Target location and same-name candidates') : tr('引用目标归属','Target location');
			const reference = `${label} ${link.target || link.source}${link.fragment ?? ''}`;
			const target = found.status === 'missing' ? tr('目标文件不存在。','The target file is missing.')
				: cross ? `${tr('库外目标','Target outside this library')} ${cross.evidence}` : `${tr('库内目标','Target in this library')} ${found.path}`;
			const candidates = matching || (matches.length === 1 && tr('只找到一个同名候选。','Found one same-name candidate.'));
			recordChecked(check,position.file,[details,reference].filter(Boolean).join(' · '),[target,candidates].filter(Boolean).join(' · '),position.line);
		}
		if (cross) {
			check.diagnostics.push({...position,evidence:[cross.evidence,details,matching].filter(Boolean).join(' · '),
				severity:'warning',code:'external-library-dependency',message:cross.library
					? tr('单独移动或克隆本库时需要目标所属库。','Keep the target library available when moving or cloning this library on its own.')
					: tr('单独移动或克隆本库时需要外部目标文件。','Keep the external target file available when moving or cloning this library on its own.')});
		} else if (matching) {
			check.diagnostics.push({...position,severity:'info',code:'same-name-candidates',
				evidence:[found.path && tr('实际目标','Resolved target') + ' ' + found.path,details,matching].filter(Boolean).join(' · '),
				message:tr('链接存在多个同名候选。','Several files share this link name. Use the target path to disambiguate.')});
		}
	}
	for (const [index,note] of notes.entries()) {
		noteCoverage(check,note,tools);
		for (const [i,ref] of note.references.entries()) {
			const position = {file:note.file,line:ref.line};
			if (ref.kind === 'local') inspect(ref,candidateMatches[index][i],position);
			else if (ref.kind === 'template') recordLinkPlaceholder(check,ref.placeholder,position);
		}
	}
	noteLinkCoverage(check,tools);
	let deferred = false, unresolved = false;
	for (const [i,canvas] of canvases.entries()) {
		const {file,data,references,unreadable,malformed} = canvas;
		function uninspectable(code, message, evidence) {
			check.coverage.unknown++;
			unresolved = true;
			check.diagnostics.push({file,evidence,code,message,severity:'info'});
		}
		if (unreadable) {
			check.coverage.unknown++;
			check.diagnostics.push({severity:'info',code:'unreadable-file',file,message:tr('文件不可读或超出检查范围限制。','Could not read the file within the scan limits.')});
			addReason(check,tr('部分检查文件未能读取。','Some files for this check could not be read.'));
			continue;
		}
		if (malformed) {uninspectable('canvas-json',tr('Canvas 内容不是有效 JSON。','The Canvas file contains invalid JSON.')); continue;}
		if (!isRecord(data) || (data.nodes !== undefined && !Array.isArray(data.nodes))) {
			uninspectable('canvas-structure',tr('Canvas 须含可选的节点与连线数组。','Use arrays for nodes and edges when those fields are present.'));
			continue;
		}
		for (const [n,node] of (data.nodes ?? []).entries()) {
			if (!canInspectNode(node)) {uninspectable('canvas-node',tr('Canvas 节点的 ID、类型、坐标、尺寸或颜色无效。','Check the Canvas node’s ID, type, coordinates, dimensions, and color.')); continue;}
			const nodeLabel = tr('节点','Node') + (validText(node.id,128) ? ' ' + node.id : '');
			if (node.type === 'text' && typeof node.text !== 'string') {
				uninspectable('canvas-text-node',tr('Canvas 文本节点没有文本。','Supply a text string for the Canvas text node.'),nodeLabel);
				continue;
			}
			const refs = references[n];
			if (!refs.length && (node.type === 'file' || node.type === 'group' && node.background !== undefined)) {
				uninspectable('canvas-file-path',tr('Canvas 文件路径不是有效的 Vault 相对路径。','Use a valid vault-relative path for the Canvas file reference.'),nodeLabel);
				continue;
			}
			for (const [r,ref] of refs.entries()) {
				const details = nodeLabel + (ref.line ? ' · ' + tr('文本行','Text line') + ' ' + ref.line : '');
				if (ref.kind === 'external') {check.coverage.skipped++; continue;}
				if (ref.kind === 'invalid-encoding') {
					uninspectable('canvas-link-encoding',tr('Canvas 文本节点的链接包含无效 URL 转义。','The Canvas text node contains a link with invalid URL encoding.'),details);
					continue;
				}
				if (ref.kind === 'template') {
					recordLinkPlaceholder(check,ref.placeholder,{file,evidence:details},!canvasIncluded);
					if (ref.placeholder.coverage === 'skipped') deferred = true;
					if (ref.placeholder.coverage === 'unknown') unresolved = true;
					continue;
				}
				inspect(ref,canvasMatches[i][n][r],{file},details);
				if (ref.found.status === 'unknown') {
					unresolved = true;
					const exact = ref.link.canvasPath;
					check.diagnostics.push({file,evidence:[ref.evidence,details].filter(Boolean).join(' · '),severity:'info',code:exact ? 'canvas-target-unverified' : 'canvas-text-link-unverified',
						message:validText(ref.found.reason,512) ? ref.found.reason : exact
							? tr('未能确认 Canvas 引用的文件。','Could not verify the Canvas file reference.')
							: tr('未能确认 Canvas 文本节点中的链接。','Could not verify the link in the Canvas text node.')});
				}
			}
		}
	}
	if (deferred) addReason(check,tr('Canvas 中的部分模板链接待实例化后检查。','Check deferred Canvas template links after their variables are filled in.'));
	if (unresolved) addReason(check,tr('部分 Canvas 引用或链接未能确认。','Some Canvas references or links could not be verified.'));
	return check;
}
